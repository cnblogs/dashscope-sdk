using System.Text;
using Cnblogs.DashScope.Core;

namespace Cnblogs.DashScope.Sample.Text;

public class PptGenerationSample : TextSample
{
    /// <inheritdoc />
    public override string Description => "Generate PPT with qwen-doc-turbo";

    /// <inheritdoc />
    public override async Task RunAsync(IDashScopeClient client)
    {
        var messages = new List<TextChatMessage>
        {
            TextChatMessage.System("You are a helpful assistant"),
            TextChatMessage.DocUrl("生成一个ppt", ["https://help-static-aliyun-doc.aliyuncs.com/file-manage-files/zh-CN/20251107/jockge/%E7%A4%BA%E4%BE%8B%E4%BA%A7%E5%93%81%E6%89%8B%E5%86%8CA.docx"]),
        };
        messages.ForEach(m => Console.WriteLine($"{m.Role} > {m.Content}"));
        var completion = client.GetTextCompletionStreamAsync(
            new ModelRequest<TextGenerationInput, ITextGenerationParameters>()
            {
                Model = "qwen-doc-turbo",
                Input = new TextGenerationInput() { Messages = messages },
                Parameters = new TextGenerationParameters()
                {
                    ResultFormat = "message",
                    IncrementalOutput = true,
                    Skill = [DashScopeModelSkill.PptCreative]
                }
            });
        var reply = new StringBuilder();
        var reasoning = false;
        TextGenerationTokenUsage? usage = null;
        await foreach (var chunk in completion)
        {
            var choice = chunk.Output.Choices![0];
            if (string.IsNullOrEmpty(choice.Message.ReasoningContent) == false)
            {
                if (reasoning == false)
                {
                    reasoning = true;
                    Console.Write("Reasoning > ");
                }

                Console.WriteLine(choice.Message.ReasoningContent);
            }

            if (string.IsNullOrWhiteSpace(choice.Message.Content.Text) == false)
            {
                if (reasoning)
                {
                    reasoning = false;
                    Console.WriteLine();
                    Console.Write("Assistant > ");
                }

                Console.Write(choice.Message.Content);
                reply.Append(choice.Message.Content);
            }

            usage = chunk.Usage;
        }

        Console.WriteLine();
        messages.Add(TextChatMessage.Assistant(reply.ToString()));
        if (usage != null)
        {
            Console.WriteLine($"Usage: in({usage.InputTokens})/out({usage.OutputTokens})/total({usage.TotalTokens})");
        }
    }
}

