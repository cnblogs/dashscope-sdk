namespace Cnblogs.DashScope.Core;

/// <summary>
/// A conversation item of an omni realtime session. Which members are present depends on
/// <see cref="Type"/>: a message item carries Role and Content, a function_call item (the model
/// asks the client to execute a function) carries CallId, Name and Arguments, a mcp_call item
/// (the server executed a remote MCP tool) carries them as well plus ServerLabel, the Output and
/// - when it failed - the Error, a mcp_list_tools item carries ServerLabel and the discovered
/// Tools, and a mcp_approval_request item (the server asks the client to approve an MCP call)
/// carries ServerLabel, Name, Arguments and CallId.
/// </summary>
public class OmniRealtimeItem
{
    /// <summary>
    /// The id of the item. Generated by the server, an id of a created item is not taken over.
    /// </summary>
    public string? Id { get; set; }

    /// <summary>
    /// realtime.item for the message, function_call and function_call_output items. Server echo.
    /// </summary>
    public string? Object { get; set; }

    /// <summary>
    /// The type of the item: message, function_call, function_call_output (the client writes the
    /// result of a function call back), mcp_list_tools, mcp_call or mcp_approval_response (the
    /// client answers an MCP approval request).
    /// </summary>
    public string? Type { get; set; }

    /// <summary>
    /// The status of the item, e.g. in_progress, completed; incomplete for the message of a
    /// cancelled response. Server echo.
    /// </summary>
    public string? Status { get; set; }

    /// <summary>
    /// The role of a message item: system, user or assistant.
    /// </summary>
    public string? Role { get; set; }

    /// <summary>
    /// The content of a message item: user items take input_text parts, assistant items are
    /// written by the server.
    /// </summary>
    public List<OmniRealtimeItemContent>? Content { get; set; }

    /// <summary>
    /// The id of the call, correlating a function_call item with its function_call_output item.
    /// Take it from the response.function_call_arguments.done event or the output of the
    /// response.done event.
    /// </summary>
    public string? CallId { get; set; }

    /// <summary>
    /// The name of the function or of the MCP tool.
    /// </summary>
    public string? Name { get; set; }

    /// <summary>
    /// The arguments of the call as a JSON string.
    /// </summary>
    public string? Arguments { get; set; }

    /// <summary>
    /// The output of the function call as a JSON string. function_call_output items.
    /// </summary>
    public string? Output { get; set; }

    /// <summary>
    /// The label of the MCP server the tool belongs to.
    /// </summary>
    public string? ServerLabel { get; set; }

    /// <summary>
    /// The tools discovered on the MCP server, empty when the discovery failed. mcp_list_tools
    /// items.
    /// </summary>
    public List<OmniRealtimeMcpTool>? Tools { get; set; }

    /// <summary>
    /// The error of a failed tool discovery or tool call.
    /// </summary>
    public OmniRealtimeError? Error { get; set; }

    /// <summary>
    /// The id of the approval request being answered, the id of the mcp_approval_request item.
    /// mcp_approval_response items.
    /// </summary>
    public string? ApprovalRequestId { get; set; }

    /// <summary>
    /// Whether to approve the MCP tool call; a rejection fails the call. mcp_approval_response
    /// items.
    /// </summary>
    public bool? Approve { get; set; }
}
